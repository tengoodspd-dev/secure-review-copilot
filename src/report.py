from __future__ import annotations
from datetime import datetime
from src.analyser import Finding, Severity


def generate_markdown(findings: list[Finding], meta: dict[str, str]) -> str:
    """Generate a Markdown security report.

    Args:
        findings: List of Finding objects from run_analysis.
        meta: Metadata dict; expects key "system_name".

    Returns:
        A Markdown-formatted string representing the full security report.
    """
    system_name = meta.get("system_name", "Unknown System")
    scan_time = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    critical = [f for f in findings if f.severity == Severity.CRITICAL]
    high     = [f for f in findings if f.severity == Severity.HIGH]
    medium   = [f for f in findings if f.severity == Severity.MEDIUM]
    low      = [f for f in findings if f.severity == Severity.LOW]
    info     = [f for f in findings if f.severity == Severity.INFO]

    lines = [
        f"# Security Review Report — {system_name}",
        f"",
        f"**Scan Date:** {scan_time}  ",
        f"**Total Findings:** {len(findings)}  ",
        f"**Critical:** {len(critical)} | **High:** {len(high)} | **Medium:** {len(medium)} | **Low:** {len(low)} | **Info:** {len(info)}",
        f"",
        f"---",
        f"",
        f"## Executive Summary",
        f"",
    ]

    if not findings:
        lines.append("No security issues were detected in the provided configuration.")
    else:
        lines.append(
            f"The analysis identified **{len(findings)} finding(s)** across {system_name}. "
            f"{'Immediate action is required for CRITICAL findings.' if critical else 'No critical issues found.'}"
        )

    lines += ["", "## Findings", ""]

    if findings:
        lines += [
            "| Control ID | Title | Severity | Remediation |",
            "|------------|-------|----------|-------------|",
        ]
        for f in findings:
            lines.append(f"| {f.control_id} | {f.title} | {f.severity.value} | {f.remediation} |")
    else:
        lines.append("_No findings._")

    lines += ["", "## Remediation Checklist", ""]
    checklist_items = [f for f in findings if f.severity in (Severity.CRITICAL, Severity.HIGH)]
    if checklist_items:
        for f in checklist_items:
            lines.append(f"- [ ] **[{f.severity.value}]** {f.control_id} — {f.title}")
    else:
        lines.append("_No critical or high-severity items require immediate action._")

    lines += ["", "---", "_Report generated by SecureReview Copilot_"]
    return "\n".join(lines)
